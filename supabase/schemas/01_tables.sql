-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";

-- Private schema (used by sales policies migration)
create schema if not exists "private";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb,
    continent text,
    network text,
    headcount integer,
    headcount_source text,
    current_competitor text,
    is_client boolean not null default true,
    is_referral boolean not null default false,
    is_placeholder boolean not null default false,
    referred_by_company_id bigint,
    constraint companies_category_check check (is_placeholder or is_client or is_referral),
    constraint companies_referred_by_not_self_check check (referred_by_company_id <> id)
);

-- Only one placeholder company ("Por definir") can exist.
create unique index companies_single_placeholder_idx on public.companies using btree (is_placeholder) where is_placeholder;

