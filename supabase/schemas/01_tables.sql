-- Humand contracts: fee history, commission and sub-commission rules (admins only)
create table public.contracts (
    id bigint generated by default as identity primary key,
    company_id bigint not null,
    deal_id bigint,
    referral_company_id bigint,
    -- first day of the month of the client's first payment: contract month 1
    first_payment_month date,
    -- first day of the last month billed, when the contract ended
    end_month date,
    -- [{"from_month": "2026-11", "amount": 1200}]
    fee_history jsonb not null default '[]'::jsonb,
    -- [{"from_month": 1, "to_month": 12, "percent": 50}]
    commission_rules jsonb not null default '[]'::jsonb,
    -- [{"kind": "percent" | "fixed", "value": 20, "from_month": 1, "to_month": null}]
    subcommission_rules jsonb not null default '[]'::jsonb,
    notes text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint contracts_fee_history_is_array check (jsonb_typeof(fee_history) = 'array'),
    constraint contracts_commission_rules_is_array check (jsonb_typeof(commission_rules) = 'array'),
    constraint contracts_subcommission_rules_is_array check (jsonb_typeof(subcommission_rules) = 'array'),
    constraint contracts_first_payment_month_is_month check (extract(day from first_payment_month) = 1),
    constraint contracts_end_month_is_month check (extract(day from end_month) = 1),
    constraint contracts_end_after_start check (end_month >= first_payment_month),
    constraint contracts_referral_not_self check (referral_company_id <> company_id)
);

create table public.subcommission_payments (
    id bigint generated by default as identity primary key,
    contract_id bigint not null,
    -- first day of the month the sub-commission is for
    month date not null,
    status text not null default 'pending',
    -- amount computed when it was marked paid
    amount numeric(12, 2),
    paid_at date,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint subcommission_payments_status_check check (status in ('pending', 'paid')),
    constraint subcommission_payments_month_is_month check (extract(day from month) = 1)
);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

