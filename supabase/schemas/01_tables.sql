create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    category text,
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    lost_reason text,
    lost_reason_detail text,
    lost_at timestamp with time zone,
    postponed_until date,
    postponed_reason text,
    postponed_at timestamp with time zone,
    -- A lost deal has a reason, a postponed deal has a date and a reason
    constraint deals_lost_reason_required check (stage <> 'lost' or lost_reason is not null),
    constraint deals_postponed_details_required check (
        stage <> 'postponed' or (postponed_until is not null and postponed_reason is not null)
    )
);

-- Tags ("post-its") applied to a deal while it sits in a stage. Removed tags
-- are kept (removed_at set) as the deal history.
create table public.deal_tag_assignments (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    stage text not null,
    tag_value text not null,
    description text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone,
    updated_by bigint,
    removed_at timestamp with time zone,
    removed_reason text,
    constraint deal_tag_assignments_description_length check (char_length(description) <= 200),
    constraint deal_tag_assignments_removed_reason_check check (removed_reason in ('stage_change', 'manual'))
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
