-- Humand contracts and billing.
-- A contract records what a client company pays Humand every month (the fee,
-- with its history), the commission Humand pays on that fee (a % by contract
-- month, counted from the client's first payment), and the sub-commission
-- owed to the referral company that introduced the client (fixed amounts or
-- a % of the commission, each for a range of contract months).
-- Sub-commission payments record, month by month, whether it was paid.
-- Only administrators can read or change any of it.

-- 1. Contracts
create table if not exists public.contracts (
    id bigint generated by default as identity primary key,
    company_id bigint not null,
    deal_id bigint,
    referral_company_id bigint,
    -- first day of the month of the client's first payment: contract month 1
    first_payment_month date,
    -- first day of the last month billed, when the contract ended
    end_month date,
    -- [{"from_month": "2026-11", "amount": 1200}]
    fee_history jsonb not null default '[]'::jsonb,
    -- [{"from_month": 1, "to_month": 12, "percent": 50}]
    commission_rules jsonb not null default '[]'::jsonb,
    -- [{"kind": "percent" | "fixed", "value": 20, "from_month": 1, "to_month": null}]
    subcommission_rules jsonb not null default '[]'::jsonb,
    notes text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint contracts_fee_history_is_array check (jsonb_typeof(fee_history) = 'array'),
    constraint contracts_commission_rules_is_array check (jsonb_typeof(commission_rules) = 'array'),
    constraint contracts_subcommission_rules_is_array check (jsonb_typeof(subcommission_rules) = 'array'),
    constraint contracts_first_payment_month_is_month check (extract(day from first_payment_month) = 1),
    constraint contracts_end_month_is_month check (extract(day from end_month) = 1),
    constraint contracts_end_after_start check (end_month >= first_payment_month),
    constraint contracts_referral_not_self check (referral_company_id <> company_id)
);

alter table public.contracts drop constraint if exists contracts_company_id_fkey;
alter table public.contracts
    add constraint contracts_company_id_fkey foreign key (company_id) references public.companies(id) on delete cascade;
alter table public.contracts drop constraint if exists contracts_deal_id_fkey;
alter table public.contracts
    add constraint contracts_deal_id_fkey foreign key (deal_id) references public.deals(id) on delete set null;
alter table public.contracts drop constraint if exists contracts_referral_company_id_fkey;
alter table public.contracts
    add constraint contracts_referral_company_id_fkey foreign key (referral_company_id) references public.companies(id) on delete set null;
alter table public.contracts drop constraint if exists contracts_sales_id_fkey;
alter table public.contracts
    add constraint contracts_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;

create index if not exists contracts_company_id_idx on public.contracts using btree (company_id);
create index if not exists contracts_referral_company_id_idx on public.contracts using btree (referral_company_id);
-- A won deal leads to one contract at most
create unique index if not exists contracts_deal_id_unique_idx on public.contracts using btree (deal_id) where deal_id is not null;

-- 2. Sub-commission payments, one row per contract and month at most
create table if not exists public.subcommission_payments (
    id bigint generated by default as identity primary key,
    contract_id bigint not null,
    -- first day of the month the sub-commission is for
    month date not null,
    status text not null default 'pending',
    -- amount computed when it was marked paid
    amount numeric(12, 2),
    paid_at date,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint subcommission_payments_status_check check (status in ('pending', 'paid')),
    constraint subcommission_payments_month_is_month check (extract(day from month) = 1)
);

alter table public.subcommission_payments drop constraint if exists subcommission_payments_contract_id_fkey;
alter table public.subcommission_payments
    add constraint subcommission_payments_contract_id_fkey foreign key (contract_id) references public.contracts(id) on delete cascade;

create unique index if not exists subcommission_payments_contract_month_idx
    on public.subcommission_payments using btree (contract_id, month);

-- 3. Administrators only
alter table public.contracts enable row level security;
alter table public.subcommission_payments enable row level security;

drop policy if exists "Contracts admin access" on public.contracts;
create policy "Contracts admin access" on public.contracts for all to authenticated
    using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Subcommission payments admin access" on public.subcommission_payments;
create policy "Subcommission payments admin access" on public.subcommission_payments for all to authenticated
    using (public.is_admin()) with check (public.is_admin());

grant all on table public.contracts to authenticated;
grant all on table public.contracts to service_role;
grant all on table public.subcommission_payments to authenticated;
grant all on table public.subcommission_payments to service_role;
grant all on sequence public.contracts_id_seq to authenticated;
grant all on sequence public.contracts_id_seq to service_role;
grant all on sequence public.subcommission_payments_id_seq to authenticated;
grant all on sequence public.subcommission_payments_id_seq to service_role;

-- 4. Owner and last change
CREATE OR REPLACE FUNCTION "public"."touch_updated_at"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.updated_at := now();
  return new;
end;
$$;

grant all on function public.touch_updated_at() to anon;
grant all on function public.touch_updated_at() to authenticated;
grant all on function public.touch_updated_at() to service_role;

create or replace trigger set_contract_sales_id_trigger
    before insert on public.contracts
    for each row execute function public.set_sales_id_default();

create or replace trigger touch_contracts_updated_at
    before update on public.contracts
    for each row execute function public.touch_updated_at();

create or replace trigger touch_subcommission_payments_updated_at
    before update on public.subcommission_payments
    for each row execute function public.touch_updated_at();
