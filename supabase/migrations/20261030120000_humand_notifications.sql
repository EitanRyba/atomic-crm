-- Humand notifications and Google Calendar.
-- 1. In-app notifications (the bell), written by the daily and weekly digest.
-- 2. Each user can connect their Google Calendar: tasks with a due date
--    become calendar events, kept in sync when tasks change.
-- Tokens and OAuth states are only reachable by the edge functions (service
-- role): no policy lets a signed-in user read them.

-- 1. Notifications
create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    sales_id bigint not null,
    kind text not null,
    title text not null,
    body text,
    -- in-app path to open, e.g. "/deals/12/show"
    link text,
    created_at timestamp with time zone not null default now(),
    read_at timestamp with time zone
);

alter table public.notifications drop constraint if exists notifications_sales_id_fkey;
alter table public.notifications
    add constraint notifications_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

create index if not exists notifications_sales_id_created_at_idx
    on public.notifications using btree (sales_id, created_at desc);

alter table public.notifications enable row level security;

-- A user reads, and marks as read, their own notifications only
drop policy if exists "Notifications read own" on public.notifications;
create policy "Notifications read own" on public.notifications for select to authenticated
    using (sales_id in (select id from public.sales where user_id = auth.uid()));
drop policy if exists "Notifications update own" on public.notifications;
create policy "Notifications update own" on public.notifications for update to authenticated
    using (sales_id in (select id from public.sales where user_id = auth.uid()))
    with check (sales_id in (select id from public.sales where user_id = auth.uid()));
drop policy if exists "Notifications delete own" on public.notifications;
create policy "Notifications delete own" on public.notifications for delete to authenticated
    using (sales_id in (select id from public.sales where user_id = auth.uid()));

grant select, update, delete on table public.notifications to authenticated;
grant all on table public.notifications to service_role;
grant all on sequence public.notifications_id_seq to service_role;

-- 2. Google Calendar
create table if not exists public.google_calendar_connections (
    sales_id bigint primary key,
    google_email text,
    refresh_token text not null,
    calendar_id text not null default 'primary',
    connected_at timestamp with time zone not null default now()
);

alter table public.google_calendar_connections drop constraint if exists google_calendar_connections_sales_id_fkey;
alter table public.google_calendar_connections
    add constraint google_calendar_connections_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

create table if not exists public.google_oauth_states (
    state uuid primary key default gen_random_uuid(),
    sales_id bigint not null,
    return_to text not null,
    created_at timestamp with time zone not null default now()
);

alter table public.google_oauth_states drop constraint if exists google_oauth_states_sales_id_fkey;
alter table public.google_oauth_states
    add constraint google_oauth_states_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

-- RLS on, no policy: only the service role (edge functions) can use them
alter table public.google_calendar_connections enable row level security;
alter table public.google_oauth_states enable row level security;
revoke all on table public.google_calendar_connections from anon, authenticated;
revoke all on table public.google_oauth_states from anon, authenticated;
grant all on table public.google_calendar_connections to service_role;
grant all on table public.google_oauth_states to service_role;

-- The calendar event of each task
alter table public.tasks add column if not exists google_event_id text;

-- Whether the signed-in user connected a calendar, without exposing tokens
CREATE OR REPLACE FUNCTION "public"."google_calendar_status"() RETURNS TABLE("connected" boolean, "google_email" "text")
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select c.sales_id is not null, c.google_email
  from public.sales s
  left join public.google_calendar_connections c on c.sales_id = s.id
  where s.user_id = auth.uid();
$$;

revoke all on function public.google_calendar_status() from public;
grant execute on function public.google_calendar_status() to authenticated;
grant execute on function public.google_calendar_status() to service_role;
